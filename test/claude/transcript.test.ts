import { describe, it, expect } from 'vitest';
import {
  parseTranscript,
  groupTurns,
  findAnchorIndex,
  findUuidIndex,
  summarizeTools,
  renderTurn,
  planImport,
  normalizeForMatch,
  transcriptCwd,
} from '../../src/claude/transcript.js';

/** Build a transcript line the way the CLI writes them. */
function line(entry: Record<string, unknown>): string {
  return JSON.stringify(entry);
}

function userPrompt(uuid: string, text: string, extra: Record<string, unknown> = {}): string {
  return line({ type: 'user', uuid, timestamp: '2026-07-30T12:00:00.000Z', message: { role: 'user', content: text }, ...extra });
}

function assistantText(uuid: string, text: string, extra: Record<string, unknown> = {}): string {
  return line({
    type: 'assistant',
    uuid,
    timestamp: '2026-07-30T12:00:01.000Z',
    message: { role: 'assistant', content: [{ type: 'text', text }] },
    ...extra,
  });
}

function toolUse(uuid: string, id: string, name: string): string {
  return line({
    type: 'assistant',
    uuid,
    message: { role: 'assistant', content: [{ type: 'tool_use', id, name, input: {} }] },
  });
}

function toolResult(uuid: string, toolUseId: string, isError = false): string {
  return line({
    type: 'user',
    uuid,
    message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: toolUseId, content: 'ok', is_error: isError }] },
  });
}

describe('parseTranscript', () => {
  it('keeps prompts, assistant text and tool calls in order', () => {
    const raw = [
      userPrompt('u1', 'fix the sort order'),
      assistantText('a1', 'On it.'),
      toolUse('a2', 'tool_1', 'Read'),
      toolResult('u2', 'tool_1'),
      assistantText('a3', 'Done.'),
    ].join('\n');

    expect(parseTranscript(raw).map((e) => e.kind)).toEqual([
      'prompt', 'text', 'tool', 'tool_result', 'text',
    ]);
  });

  it('drops thinking blocks, sidechains, meta entries and CLI bookkeeping', () => {
    const raw = [
      line({ type: 'queue-operation', uuid: 'q1' }),
      line({ type: 'file-history-snapshot', uuid: 'f1' }),
      line({ type: 'ai-title', uuid: 't1' }),
      line({ type: 'system', subtype: 'turn_duration', uuid: 's1' }),
      line({ type: 'attachment', uuid: 'at1' }),
      line({
        type: 'assistant',
        uuid: 'a1',
        message: { role: 'assistant', content: [{ type: 'thinking', thinking: 'hmm' }] },
      }),
      assistantText('a2', 'subagent chatter', { isSidechain: true }),
      userPrompt('u1', 'a meta note', { isMeta: true }),
      assistantText('a3', 'real reply'),
    ].join('\n');

    const events = parseTranscript(raw);
    expect(events).toHaveLength(1);
    expect(events[0]).toMatchObject({ kind: 'text', text: 'real reply' });
  });

  it('drops slash-command plumbing and local command output', () => {
    const raw = [
      userPrompt('u1', '<command-name>/clear</command-name>'),
      userPrompt('u2', '<local-command-stdout>done</local-command-stdout>'),
      userPrompt('u3', 'Caveat: The messages below were generated by the user while running local commands. blah'),
      userPrompt('u4', 'actually do the thing'),
    ].join('\n');

    const events = parseTranscript(raw);
    expect(events).toHaveLength(1);
    expect(events[0]).toMatchObject({ kind: 'prompt', text: 'actually do the thing' });
  });

  it('survives malformed lines', () => {
    const raw = ['{not json', '', userPrompt('u1', 'still works')].join('\n');
    expect(parseTranscript(raw)).toHaveLength(1);
  });

  it('reads the cwd from the first entry that records one', () => {
    const raw = [line({ type: 'queue-operation' }), line({ type: 'user', cwd: 'E:\\repos\\thing' })].join('\n');
    expect(transcriptCwd(raw)).toBe('E:\\repos\\thing');
  });
});

describe('groupTurns', () => {
  it('opens a turn on each prompt and gathers the work under it', () => {
    const events = parseTranscript([
      userPrompt('u1', 'first ask'),
      assistantText('a1', 'reply one'),
      toolUse('a2', 'tool_1', 'Read'),
      toolResult('u2', 'tool_1'),
      userPrompt('u3', 'second ask'),
      assistantText('a4', 'reply two'),
    ].join('\n'));

    const turns = groupTurns(events);
    expect(turns).toHaveLength(2);
    expect(turns[0]).toMatchObject({ prompt: 'first ask', texts: ['reply one'], tools: ['Read'], toolErrors: 0 });
    expect(turns[1]).toMatchObject({ prompt: 'second ask', texts: ['reply two'], tools: [] });
  });

  it('gathers assistant output that precedes any prompt into a leading turn', () => {
    const turns = groupTurns(parseTranscript([
      assistantText('a1', 'resumed mid-flight'),
      userPrompt('u1', 'ok continue'),
    ].join('\n')));

    expect(turns[0]).toMatchObject({ prompt: undefined, texts: ['resumed mid-flight'] });
    expect(turns[1]).toMatchObject({ prompt: 'ok continue' });
  });

  it('counts tool errors, but only for calls inside the window', () => {
    const withCall = groupTurns(parseTranscript([
      userPrompt('u1', 'go'),
      toolUse('a1', 'tool_1', 'Bash'),
      toolResult('u2', 'tool_1', true),
    ].join('\n')));
    expect(withCall[0]!.toolErrors).toBe(1);

    // A result whose tool_use was cut off by the import window shouldn't count.
    const orphaned = groupTurns(parseTranscript([
      userPrompt('u1', 'go'),
      toolResult('u2', 'tool_from_before', true),
    ].join('\n')));
    expect(orphaned[0]!.toolErrors).toBe(0);
  });

  it('tracks the last event uuid as the watermark', () => {
    const turns = groupTurns(parseTranscript([
      userPrompt('u1', 'go'),
      assistantText('a1', 'first'),
      assistantText('a2', 'last'),
    ].join('\n')));
    expect(turns[0]!.lastUuid).toBe('a2');
  });
});

describe('findAnchorIndex', () => {
  const events = parseTranscript([
    userPrompt('u1', 'the very first thing I asked about the report history page'),
    assistantText('a1', 'Picking up where I was cut off — I had confirmed the gap and verified the backend.'),
    userPrompt('u2', 'process died again. Continue your work on the date handling please'),
    assistantText('a2', 'Understood, I will stop asking and make the calls myself from here on.'),
  ].join('\n'));

  it('anchors on the newest transcript text already visible in Discord', () => {
    const index = findAnchorIndex(events, [
      'the very first thing I asked about the report history page',
      'Picking up where I was cut off — I had confirmed the gap and verified the backend.',
    ]);
    expect(index).toBe(1);
  });

  it('matches despite whitespace and case differences from Discord rendering', () => {
    const index = findAnchorIndex(events, ['PICKING UP where I was cut off —  I had confirmed\nthe gap and verified the backend.']);
    expect(index).toBe(1);
  });

  it('matches a Discord message that truncated a long transcript reply', () => {
    const long = 'a'.repeat(50) + ' this tail was cut off by Discord';
    const withLong = parseTranscript(assistantText('a9', long));
    expect(findAnchorIndex(withLong, ['a'.repeat(50) + ' this tail'])).toBe(-1);
    expect(findAnchorIndex(withLong, [long.slice(0, 80) + '…(truncated)'])).toBe(0);
  });

  it('returns -1 when nothing matches, and ignores too-short messages', () => {
    expect(findAnchorIndex(events, ['completely unrelated channel chatter here'])).toBe(-1);
    expect(findAnchorIndex(events, ['ok'])).toBe(-1);
  });

  it('finds an entry by uuid for watermark resumption', () => {
    expect(findUuidIndex(events, 'a1')).toBe(1);
    expect(findUuidIndex(events, 'nope')).toBe(-1);
  });
});

describe('summarizeTools', () => {
  it('counts calls and orders by frequency', () => {
    expect(summarizeTools(['Read', 'Bash', 'Read', 'Edit', 'Read', 'Bash'])).toBe('Read ×3, Bash ×2, Edit');
  });

  it('is empty for no tools', () => {
    expect(summarizeTools([])).toBe('');
  });
});

describe('renderTurn', () => {
  it('renders prompt, prose and one tool-summary line', () => {
    const [turn] = groupTurns(parseTranscript([
      userPrompt('u1', 'do the thing'),
      assistantText('a1', 'Doing it.'),
      toolUse('a2', 'tool_1', 'Read'),
      toolUse('a3', 'tool_2', 'Read'),
      toolResult('u2', 'tool_1'),
      assistantText('a4', 'Done.'),
    ].join('\n')));

    const rendered = renderTurn(turn!);
    expect(rendered.map((m) => m.title)).toEqual(['📝 Prompt (offline)', '💬 Claude', '💬 Claude', undefined]);
    expect(rendered[0]!.description).toBe('> do the thing');
    expect(rendered[3]!.description).toBe('🔧 2 tool calls · Read ×2');
  });

  it('flags tool errors in the summary line', () => {
    const [turn] = groupTurns(parseTranscript([
      userPrompt('u1', 'go'),
      toolUse('a1', 'tool_1', 'Bash'),
      toolResult('u2', 'tool_1', true),
    ].join('\n')));

    const summary = renderTurn(turn!).at(-1)!;
    expect(summary.description).toBe('🔧 1 tool call · Bash · ⚠️ 1 error');
    expect(summary.color).toBe(0xE67E22);
  });

  it('truncates a reply past the embed description limit', () => {
    const [turn] = groupTurns(parseTranscript(assistantText('a1', 'x'.repeat(5000))));
    const description = renderTurn(turn!)[0]!.description;
    expect(description.length).toBeLessThan(4096);
    expect(description.endsWith('…(truncated)')).toBe(true);
  });
});

describe('planImport', () => {
  const raw = [
    userPrompt('u1', 'turn one — the oldest thing in this conversation'),
    assistantText('a1', 'Reply to turn one, long enough to fingerprint reliably.'),
    userPrompt('u2', 'turn two — the message Discord already shows'),
    assistantText('a2', 'Reply to turn two, also long enough to fingerprint.'),
    userPrompt('u3', 'turn three — done offline at the CLI'),
    assistantText('a3', 'Reply to turn three, offline work.'),
  ].join('\n');
  const events = parseTranscript(raw);

  it('imports only what follows the newest message present in Discord', () => {
    const plan = planImport(events, { discordTexts: ['Reply to turn two, also long enough to fingerprint.'] });
    expect(plan.anchor).toBe('content');
    expect(plan.turns).toHaveLength(1);
    expect(plan.turns[0]!.prompt).toBe('turn three — done offline at the CLI');
    expect(plan.lastUuid).toBe('a3');
  });

  it('prefers a saved watermark over content matching', () => {
    const plan = planImport(events, {
      discordTexts: ['Reply to turn one, long enough to fingerprint reliably.'],
      watermarkUuid: 'a2',
    });
    expect(plan.anchor).toBe('watermark');
    expect(plan.turns).toHaveLength(1);
    expect(plan.turns[0]!.prompt).toBe('turn three — done offline at the CLI');
  });

  it('falls back to the last N turns when nothing anchors', () => {
    const plan = planImport(events, { discordTexts: [], fallbackTurns: 2 });
    expect(plan.anchor).toBe('fallback');
    expect(plan.turns.map((t) => t.prompt)).toEqual([
      'turn two — the message Discord already shows',
      'turn three — done offline at the CLI',
    ]);
  });

  it('imports everything when asked, ignoring the channel and the watermark', () => {
    const plan = planImport(events, { discordTexts: ['Reply to turn two, also long enough to fingerprint.'], watermarkUuid: 'a2', all: true });
    expect(plan.anchor).toBe('all');
    expect(plan.turns).toHaveLength(3);
  });

  it('reports nothing to import when the channel is already current', () => {
    const plan = planImport(events, { discordTexts: ['Reply to turn three, offline work.'] });
    expect(plan.turns).toHaveLength(0);
    expect(plan.messages).toHaveLength(0);
    expect(plan.lastUuid).toBeUndefined();
  });

  it('drops the oldest turns to stay under the message cap', () => {
    const plan = planImport(events, { all: true, maxMessages: 4 });
    expect(plan.droppedTurns).toBe(1);
    expect(plan.messages.length).toBeLessThanOrEqual(4);
    expect(plan.turns[0]!.prompt).toBe('turn two — the message Discord already shows');
  });
});

describe('normalizeForMatch', () => {
  it('collapses whitespace and lowercases', () => {
    expect(normalizeForMatch('  Hello\n\n  World  ')).toBe('hello world');
  });
});
