import * as fs from "fs";
import * as os from "os";
import * as path from "path";

/**
 * Reading Claude CLI session transcripts (`~/.claude/projects/<mangled-cwd>/<session-id>.jsonl`)
 * and turning them into Discord-postable history.
 *
 * This exists for `/online`: work done in the CLI (while the bot was down, or
 * away from Discord) leaves no trace in the channel. Replaying the transcript
 * brings that offline work back into the thread so the channel stays the record
 * of the conversation. It is strictly read-only — nothing here talks to the CLI.
 */

/** A conversation event worth showing in Discord. */
export type TranscriptEvent =
  /** Something the user typed at the CLI. */
  | { kind: "prompt"; uuid: string; ts?: string; text: string }
  /** Assistant prose (thinking blocks are deliberately dropped). */
  | { kind: "text"; uuid: string; ts?: string; text: string }
  | { kind: "tool"; uuid: string; ts?: string; id: string; name: string }
  | { kind: "tool_result"; uuid: string; ts?: string; toolUseId: string; isError: boolean };

/** One prompt and everything Claude did in response to it. */
export interface TranscriptTurn {
  prompt?: string;
  /** Tool names in call order, so the summary can count them. */
  tools: string[];
  toolErrors: number;
  texts: string[];
  startedAt?: string;
  /** uuid of the last event in the turn — the import watermark. */
  lastUuid: string;
}

/** A message to post, in the same visual language as a live run. */
export interface RenderedMessage {
  title?: string;
  description: string;
  color: number;
}

// Discord caps an embed description at 4096; leave room for the truncation note.
const MAX_DESCRIPTION = 3900;

/**
 * User entries the CLI writes for its own bookkeeping rather than for the
 * conversation: slash-command plumbing, local command output, and the caveat
 * banner it injects after one. None of them are things the user "said".
 */
const SYNTHETIC_PROMPT_MARKERS = [
  "<command-name>",
  "<command-message>",
  "<command-args>",
  "<local-command-stdout>",
  "<local-command-stderr>",
  "<user-prompt-submit-hook>",
  "Caveat: The messages below were generated by the user while running local commands",
];

/** Where the CLI keeps its transcripts. */
export function claudeProjectsDir(): string {
  return path.join(os.homedir(), ".claude", "projects");
}

/**
 * Locate a session's transcript by id. The containing directory is a mangled
 * form of the session's cwd, so rather than reproduce the CLI's mangling (which
 * has changed shape before) we look for the file by name across all projects.
 */
export function findTranscriptPath(sessionId: string, projectsDir = claudeProjectsDir()): string | undefined {
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(projectsDir, { withFileTypes: true });
  } catch {
    return undefined;
  }

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const candidate = path.join(projectsDir, entry.name, `${sessionId}.jsonl`);
    if (fs.existsSync(candidate)) return candidate;
  }
  return undefined;
}

/** The cwd a transcript ran in, read from the first line that records one. */
export function transcriptCwd(rawLines: string): string | undefined {
  for (const line of rawLines.split("\n")) {
    if (!line.trim()) continue;
    try {
      const parsed = JSON.parse(line);
      if (parsed.cwd) return parsed.cwd as string;
    } catch { /* skip malformed lines */ }
  }
  return undefined;
}

function isSyntheticPrompt(text: string): boolean {
  return SYNTHETIC_PROMPT_MARKERS.some((m) => text.includes(m));
}

/**
 * Flatten a transcript into the events worth replaying. Everything the CLI
 * writes for its own use — file-history snapshots, mode changes, titles,
 * attachments, sidechain (subagent) traffic, thinking blocks — is dropped.
 */
export function parseTranscript(raw: string): TranscriptEvent[] {
  const events: TranscriptEvent[] = [];

  for (const line of raw.split("\n")) {
    if (!line.trim()) continue;

    let entry: any;
    try {
      entry = JSON.parse(line);
    } catch {
      continue;
    }

    // Subagent transcripts are interleaved into the same file; a Task's internal
    // back-and-forth isn't part of the main conversation.
    if (entry.isSidechain === true || entry.isMeta === true) continue;

    const uuid: string = entry.uuid || "";
    const ts: string | undefined = entry.timestamp;
    const content = entry.message?.content;

    if (entry.type === "user") {
      if (typeof content === "string") {
        const text = content.trim();
        if (text && !isSyntheticPrompt(text)) events.push({ kind: "prompt", uuid, ts, text });
        continue;
      }
      if (!Array.isArray(content)) continue;

      for (const block of content) {
        if (block?.type === "tool_result") {
          events.push({
            kind: "tool_result",
            uuid,
            ts,
            toolUseId: block.tool_use_id,
            isError: block.is_error === true,
          });
        } else if (block?.type === "text") {
          const text = String(block.text || "").trim();
          if (text && !isSyntheticPrompt(text)) events.push({ kind: "prompt", uuid, ts, text });
        }
      }
      continue;
    }

    if (entry.type === "assistant" && Array.isArray(content)) {
      for (const block of content) {
        if (block?.type === "text") {
          const text = String(block.text || "").trim();
          if (text) events.push({ kind: "text", uuid, ts, text });
        } else if (block?.type === "tool_use") {
          events.push({ kind: "tool", uuid, ts, id: block.id, name: block.name });
        }
      }
    }
  }

  return events;
}

/**
 * Group events into turns. A turn opens on a prompt; assistant output before the
 * first prompt (a resumed session picking up mid-flight) forms a leading turn
 * with no prompt of its own.
 */
export function groupTurns(events: TranscriptEvent[]): TranscriptTurn[] {
  const turns: TranscriptTurn[] = [];
  // Tool errors are reported against the tool_use id, which may land in a later
  // turn than the call itself — keep the mapping across turn boundaries.
  const toolNamesById = new Map<string, string>();
  let current: TranscriptTurn | undefined;

  const open = (prompt: string | undefined, ts: string | undefined, uuid: string): TranscriptTurn => {
    const turn: TranscriptTurn = { prompt, tools: [], toolErrors: 0, texts: [], startedAt: ts, lastUuid: uuid };
    turns.push(turn);
    return turn;
  };

  for (const event of events) {
    if (event.kind === "prompt") {
      current = open(event.text, event.ts, event.uuid);
      continue;
    }
    if (!current) current = open(undefined, event.ts, event.uuid);

    if (event.kind === "text") {
      current.texts.push(event.text);
    } else if (event.kind === "tool") {
      current.tools.push(event.name);
      toolNamesById.set(event.id, event.name);
    } else if (event.kind === "tool_result") {
      // Only count errors for calls we actually recorded, so a result whose call
      // predates the import window doesn't inflate this turn's error count.
      if (event.isError && toolNamesById.has(event.toolUseId)) current.toolErrors++;
    }

    current.lastUuid = event.uuid || current.lastUuid;
  }

  // A turn that is nothing but tool bookkeeping has nothing to show.
  return turns.filter((t) => t.prompt || t.texts.length > 0 || t.tools.length > 0);
}

/** Collapse whitespace so transcript text and Discord-rendered text compare equal. */
export function normalizeForMatch(text: string): string {
  return text.replace(/\s+/g, " ").trim().toLowerCase();
}

// Long enough that a match is meaningful, short enough to survive Discord's
// embed truncation of a very long message.
const FINGERPRINT_LENGTH = 80;
const MIN_FINGERPRINT_LENGTH = 24;

/**
 * The newest event index already present in Discord, matched by text. Returns -1
 * when nothing matches, which is the caller's cue to fall back to a turn count.
 *
 * Content matching rather than timestamps on purpose: the bot posts plenty of
 * messages that aren't transcript content (startup links, error embeds), and any
 * one of them arriving after the last real reply would push a timestamp anchor
 * past the very work we're trying to import.
 */
export function findAnchorIndex(events: TranscriptEvent[], discordTexts: string[]): number {
  const haystack = discordTexts.map(normalizeForMatch).filter((t) => t.length >= MIN_FINGERPRINT_LENGTH);
  if (haystack.length === 0) return -1;

  for (let i = events.length - 1; i >= 0; i--) {
    const event = events[i]!;
    if (event.kind !== "text" && event.kind !== "prompt") continue;

    const fingerprint = normalizeForMatch(event.text).slice(0, FINGERPRINT_LENGTH);
    if (fingerprint.length < MIN_FINGERPRINT_LENGTH) continue;
    if (haystack.some((h) => h.includes(fingerprint))) return i;
  }

  return -1;
}

/** Index of the event with this uuid, or -1. Used to resume from a saved watermark. */
export function findUuidIndex(events: TranscriptEvent[], uuid: string): number {
  for (let i = events.length - 1; i >= 0; i--) {
    if (events[i]!.uuid === uuid) return i;
  }
  return -1;
}

function truncate(text: string): string {
  return text.length > MAX_DESCRIPTION ? text.slice(0, MAX_DESCRIPTION) + "\n…(truncated)" : text;
}

/** "Read ×5, Bash ×4, Edit ×2" — call counts, most-used first. */
export function summarizeTools(tools: string[]): string {
  const counts = new Map<string, number>();
  for (const name of tools) counts.set(name, (counts.get(name) || 0) + 1);

  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([name, count]) => (count > 1 ? `${name} ×${count}` : name))
    .join(", ");
}

/**
 * Render a turn in condensed form: the prompt, Claude's prose, and one line
 * accounting for the tool calls. The full tool stream is what makes a live run
 * readable *as it happens*; replayed after the fact it's mostly noise, and a
 * three-day CLI session would bury the channel in hundreds of embeds.
 */
export function renderTurn(turn: TranscriptTurn): RenderedMessage[] {
  const messages: RenderedMessage[] = [];

  if (turn.prompt) {
    messages.push({
      title: "📝 Prompt (offline)",
      description: truncate(turn.prompt.split("\n").map((l) => `> ${l}`).join("\n")),
      color: 0x99AAB5,
    });
  }

  for (const text of turn.texts) {
    messages.push({ title: "💬 Claude", description: truncate(text), color: 0x7289DA });
  }

  if (turn.tools.length > 0) {
    const errors = turn.toolErrors > 0 ? ` · ⚠️ ${turn.toolErrors} error${turn.toolErrors === 1 ? "" : "s"}` : "";
    const plural = turn.tools.length === 1 ? "" : "s";
    messages.push({
      description: truncate(`🔧 ${turn.tools.length} tool call${plural} · ${summarizeTools(turn.tools)}${errors}`),
      color: turn.toolErrors > 0 ? 0xE67E22 : 0x0099FF,
    });
  }

  return messages;
}

export interface ImportPlan {
  turns: TranscriptTurn[];
  messages: RenderedMessage[];
  /** How the start point was chosen — surfaced in the summary so it's never a mystery. */
  anchor: "watermark" | "content" | "fallback" | "all";
  /** Turns dropped from the front because the plan was too large to post. */
  droppedTurns: number;
  /** Watermark to save once posted, or undefined if there's nothing to import. */
  lastUuid?: string;
}

/**
 * Decide what to import. Start point is the saved watermark, else the newest
 * transcript content already visible in Discord, else the last `fallbackTurns`
 * turns — a purged or brand-new channel shouldn't trigger a thousand-message
 * dump of an entire session's history.
 */
export function planImport(
  events: TranscriptEvent[],
  options: {
    discordTexts?: string[];
    watermarkUuid?: string;
    all?: boolean;
    fallbackTurns?: number;
    maxMessages?: number;
  } = {}
): ImportPlan {
  const { discordTexts = [], watermarkUuid, all = false, fallbackTurns = 10, maxMessages = 150 } = options;

  let anchor: ImportPlan["anchor"] = "all";
  let startIndex = 0;

  if (!all) {
    const fromWatermark = watermarkUuid ? findUuidIndex(events, watermarkUuid) : -1;
    if (fromWatermark >= 0) {
      anchor = "watermark";
      startIndex = fromWatermark + 1;
    } else {
      const fromContent = findAnchorIndex(events, discordTexts);
      if (fromContent >= 0) {
        anchor = "content";
        startIndex = fromContent + 1;
      } else {
        anchor = "fallback";
      }
    }
  }

  let turns = groupTurns(events.slice(startIndex));
  if (anchor === "fallback" && turns.length > fallbackTurns) {
    turns = turns.slice(-fallbackTurns);
  }

  // Trim from the front if the plan is too big — the most recent work is what
  // matters most, and Discord posting is the slow part.
  let droppedTurns = 0;
  let messages = turns.flatMap(renderTurn);
  while (messages.length > maxMessages && turns.length > 1) {
    turns = turns.slice(1);
    droppedTurns++;
    messages = turns.flatMap(renderTurn);
  }

  return {
    turns,
    messages,
    anchor,
    droppedTurns,
    lastUuid: turns.length > 0 ? turns[turns.length - 1]!.lastUuid : undefined,
  };
}
