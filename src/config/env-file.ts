import * as fs from 'node:fs';
import * as path from 'node:path';
import { SETTINGS, SETTING_GROUPS, SETTINGS_BY_KEY } from './settings-schema.js';
import type { Setting } from './settings-schema.js';

/**
 * Reading and writing `.env` without losing what's already in it.
 *
 * Bun loads `.env` for us at startup, but the wizard has to work under plain
 * node too, and more importantly it has to make values it *just wrote* visible
 * to a process that already did its env loading. So the bot parses the file
 * itself rather than relying on the runtime.
 *
 * Writes are surgical: existing lines are rewritten in place so the comments
 * around them survive. A `.env` that doesn't exist yet is generated whole from
 * the schema, which is how a first-run user ends up with a documented file
 * instead of three bare lines.
 */

export const ENV_FILE_NAME = '.env';

export function envFilePath(cwd: string = process.cwd()): string {
  return path.join(cwd, ENV_FILE_NAME);
}

const ASSIGNMENT = /^(\s*)(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/;
const COMMENTED_ASSIGNMENT = /^(\s*)#\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/;

function unescape(inner: string): string {
  return inner.replace(/\\([nrt"'\\])/g, (_match, char: string) => {
    switch (char) {
      case 'n':
        return '\n';
      case 'r':
        return '\r';
      case 't':
        return '\t';
      default:
        return char;
    }
  });
}

function unquote(raw: string): string {
  const value = raw.trim();
  const first = value[0];
  if (value.length >= 2 && (first === '"' || first === "'") && value.endsWith(first)) {
    const inner = value.slice(1, -1);
    return first === '"' ? unescape(inner) : inner;
  }
  // Unquoted values take an inline comment only when whitespace precedes the `#`,
  // so a value that is itself a `#` (an emoji-adjacent edge case) survives.
  return value.replace(/\s+#.*$/, '').trim();
}

export function parseEnv(contents: string): Record<string, string> {
  const result: Record<string, string> = {};
  for (const line of contents.split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    const match = ASSIGNMENT.exec(line);
    if (!match) continue;
    const key = match[2];
    if (!key) continue;
    result[key] = unquote(match[3] ?? '');
  }
  return result;
}

export function readEnvFile(file: string = envFilePath()): Record<string, string> {
  try {
    return parseEnv(fs.readFileSync(file, 'utf8'));
  } catch {
    return {};
  }
}

/**
 * Push parsed values into `process.env`.
 *
 * `override: false` is the startup path: a real environment variable always
 * beats the file (matching Bun's own precedence, and letting a launcher script
 * override without editing anything). `override: true` is the post-wizard path,
 * where the user just typed the value and clearly means it to win.
 */
export function applyEnv(
  values: Record<string, string>,
  options: { override?: boolean } = {},
): void {
  for (const [key, value] of Object.entries(values)) {
    if (!options.override && process.env[key] !== undefined) continue;
    if (value === '') {
      // An empty assignment means "unset"; leaving it as "" would defeat every
      // `process.env.X || default` read in the codebase.
      delete process.env[key];
      continue;
    }
    process.env[key] = value;
  }
}

/** Quote only when the value would otherwise be misread. Emoji stay bare. */
export function formatEnvValue(value: string): string {
  if (value === '') return '';
  if (!/[\s#"'`$\\]/.test(value)) return value;
  return `"${value.replace(/([\\"])/g, '\\$1').replace(/\n/g, '\\n').replace(/\r/g, '\\r')}"`;
}

function wrapComment(text: string, width = 76): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let current = '';
  for (const word of words) {
    if (current && current.length + 1 + word.length > width) {
      lines.push(current);
      current = word;
    } else {
      current = current ? `${current} ${word}` : word;
    }
  }
  if (current) lines.push(current);
  return lines.map((line) => `# ${line}`);
}

function settingComment(setting: Setting): string[] {
  const lines = wrapComment(setting.help);
  if (setting.choices) lines.push(`# Options: ${setting.choices.join(', ')}`);
  if (setting.default !== undefined) lines.push(`# Default: ${setting.default}`);
  return lines;
}

/**
 * Build a whole `.env` from the schema. Set values are written live; everything
 * left at its default is written commented-out, so the file doubles as
 * documentation of what else can be turned on.
 */
export function renderEnvFile(
  values: Record<string, string | null | undefined>,
  header: readonly string[] = [
    '# Configuration for the Claude Code Discord bot.',
    '# Generated by the setup wizard -- rerun it any time with: bun run config',
    '# Hand edits are preserved; the wizard rewrites values in place.',
  ],
): string {
  const lines: string[] = [...header];

  for (const group of SETTING_GROUPS) {
    const groupSettings = SETTINGS.filter((setting) => setting.group === group);
    if (groupSettings.length === 0) continue;
    lines.push('', `# ${'='.repeat(74)}`, `# ${group}`, `# ${'='.repeat(74)}`);
    for (const setting of groupSettings) {
      lines.push('', ...settingComment(setting));
      const value = values[setting.key];
      if (value === undefined || value === null || value === '') {
        lines.push(`#${setting.key}=${setting.default ?? ''}`);
      } else {
        lines.push(`${setting.key}=${formatEnvValue(value)}`);
      }
    }
  }

  lines.push('');
  return lines.join('\n');
}

/**
 * The checked-in `.env.example`, rendered from the same schema the wizard uses.
 * A test asserts the file on disk still matches, so a setting can't be added to
 * the code and quietly go undocumented.
 */
export function renderExampleEnvFile(): string {
  const values: Record<string, string | null> = {};
  for (const setting of SETTINGS) {
    // Required settings have no default to fall back on, so the example shows
    // the shape of a real value instead of an empty assignment.
    if (setting.required && setting.example) values[setting.key] = setting.example;
  }
  return renderEnvFile(values, [
    '# Example configuration for the Claude Code Discord bot.',
    '#',
    '# You do not have to fill this in by hand: run `bun run config` and the',
    '# setup wizard will write a .env for you, explaining each setting as it asks.',
    '# Copy this file to .env if you would rather edit it directly.',
  ]);
}

/**
 * Apply updates to existing file contents.
 *
 * A `null` update means "unset": the line is commented out rather than deleted,
 * so it stays where its explaining comment is and reads as a deliberate default.
 */
export function updateEnvContents(
  existing: string,
  updates: Iterable<readonly [string, string | null]>,
): string {
  const eol = existing.includes('\r\n') ? '\r\n' : '\n';
  const lines = existing.split(/\r?\n/);
  const pending = new Map(updates);
  const applied = new Set<string>();

  // Live assignments first. Every occurrence is rewritten, not just the first:
  // a duplicated key re-parses to whichever came last, so updating one and
  // leaving the other would silently discard the answer.
  for (let i = 0; i < lines.length; i++) {
    const match = ASSIGNMENT.exec(lines[i] ?? '');
    const key = match?.[2];
    if (!match || !key || !pending.has(key)) continue;
    const value = pending.get(key) ?? null;
    lines[i] = value === null ? `${match[1]}#${key}=` : `${match[1]}${key}=${formatEnvValue(value)}`;
    applied.add(key);
  }

  // Then commented placeholders, so a value being turned on for the first time
  // lands under the comment block that describes it instead of at the bottom.
  for (let i = 0; i < lines.length; i++) {
    const match = COMMENTED_ASSIGNMENT.exec(lines[i] ?? '');
    const key = match?.[2];
    if (!match || !key || !pending.has(key) || applied.has(key)) continue;
    const value = pending.get(key) ?? null;
    if (value === null) {
      applied.add(key); // already unset; nothing to do
      continue;
    }
    lines[i] = `${match[1]}${key}=${formatEnvValue(value)}`;
    applied.add(key);
  }

  const appended: string[] = [];
  for (const [key, value] of pending) {
    if (applied.has(key) || value === null) continue;
    const setting = SETTINGS_BY_KEY.get(key);
    if (setting) appended.push(`# ${setting.label}`);
    appended.push(`${key}=${formatEnvValue(value)}`);
  }

  if (appended.length > 0) {
    while (lines.length > 0 && lines[lines.length - 1] === '') lines.pop();
    lines.push('', ...appended, '');
  }

  return lines.join(eol);
}

/**
 * Persist answers. Returns the values now in effect, parsed back out of what
 * was written, so callers push exactly what's on disk into `process.env`.
 */
export function writeEnvFile(
  updates: Map<string, string | null>,
  file: string = envFilePath(),
): Record<string, string> {
  let contents: string;
  if (fs.existsSync(file)) {
    contents = updateEnvContents(fs.readFileSync(file, 'utf8'), updates);
  } else {
    const values: Record<string, string | null> = {};
    for (const [key, value] of updates) values[key] = value;
    contents = renderEnvFile(values);
  }
  fs.writeFileSync(file, contents, 'utf8');
  return parseEnv(contents);
}
